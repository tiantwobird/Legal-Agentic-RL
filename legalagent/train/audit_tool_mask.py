"""Audit the tool-result token mask on one real agentic GRPO rollout.

TRL's `GRPOTrainer(tools=...)` builds a token-level `tool_mask` while it runs the
tool loop: `1` = token generated by the policy (assistant tool call / answer),
`0` = token injected by the environment (tool response + chat-template wrapper).
The mask is multiplied into the loss, so only `1` positions receive gradients.

This script runs one step, captures the first training micro-batch, and prints
the decoded contiguous spans so the mask can be checked by eye. It also asserts
the basic invariant:

    trained_tokens + masked_tool_tokens == valid_completion_tokens

Usage:
    python -m legalagent.train.audit_tool_mask
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from ..model_io import load_model, load_tokenizer
from ..paths import RUNS, TASKS
from ..tools.agent_tools import get_compact, search_compact

SYSTEM = (
    "你是中国劳动法检索助手。工作纪律：\n"
    "1. 回答任何法律问题前，必须先调用 search_compact 检索条文；对关键条文再用 get_compact 读全文。\n"
    "2. 只依据工具返回的条文作答，引用必须来自工具返回的 article_id，不得编造。\n"
    "3. 回答给出结论 + 必要条件 + 条文 ID，控制在 200 字以内。\n"
    "4. 事实不足时明确指出缺什么，不要硬下结论。"
)


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def spans(mask: list[int]) -> list[tuple[int, int, int]]:
    """Return (start, end, value) runs of a 0/1 mask."""
    result = []
    start = 0
    for i in range(1, len(mask) + 1):
        if i == len(mask) or mask[i] != mask[start]:
            result.append((start, i, mask[start]))
            start = i
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="Qwen/Qwen3-1.7B")
    parser.add_argument("--limit", type=int, default=2)
    parser.add_argument("--max-completion-length", type=int, default=1024)
    parser.add_argument("--download", action="store_true",
                        help="允许联网下载模型（离线环境下不要加）")
    args_cli = parser.parse_args()

    import torch
    from datasets import Dataset
    from peft import LoraConfig
    from trl import GRPOConfig, GRPOTrainer

    tasks = read_jsonl(TASKS / "tasks_train_labeled.jsonl")[: args_cli.limit]
    tokenizer = load_tokenizer(args_cli.model, download=args_cli.download)
    rows = [{
        "prompt": [
            {"role": "system", "content": SYSTEM},
            {"role": "user", "content": f"{t['prompt']}\n\n适用日期：{t['applicable_date']}"},
        ],
        "task_id": t["task_id"],
    } for t in tasks]
    dataset = Dataset.from_list(rows)

    model = load_model(args_cli.model, download=args_cli.download, dtype=torch.bfloat16)

    class CapturingGRPOTrainer(GRPOTrainer):
        """Keep the first micro-batch's tensors for post-hoc inspection."""

        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self.captured = None

        def _generate_and_score_completions(self, inputs):
            output = super()._generate_and_score_completions(inputs)
            if self.captured is None:
                self.captured = {
                    key: (value.detach().cpu().clone() if torch.is_tensor(value) else value)
                    for key, value in output.items()
                }
            return output

    def reward_any(completions, **kwargs):
        # The audit only needs the rollout; keep scores non-constant so the
        # GRPO advantage path is exercised as in training.
        return [float(len(str(c)) % 5) for c in completions]

    lora = LoraConfig(
        r=8, lora_alpha=16, lora_dropout=0.05, bias="none", task_type="CAUSAL_LM",
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
    )
    grpo_args = GRPOConfig(
        output_dir=str(RUNS / "audit_tool_mask"),
        per_device_train_batch_size=len(rows),
        gradient_accumulation_steps=1,
        num_generations=2,
        max_completion_length=args_cli.max_completion_length,
        max_tool_calling_iterations=2,
        max_steps=1,
        logging_steps=1,
        save_strategy="no",
        report_to="none",
        bf16=True,
        gradient_checkpointing=True,
        use_vllm=False,
        optim="adamw_torch",
        temperature=0.9,
        chat_template_kwargs={"enable_thinking": False},
        log_completions=False,
    )

    trainer = CapturingGRPOTrainer(
        model=model, args=grpo_args, processing_class=tokenizer,
        reward_funcs=[reward_any], train_dataset=dataset,
        tools=[search_compact, get_compact], peft_config=lora,
    )
    trainer.train()

    captured = trainer.captured
    if captured is None or captured.get("tool_mask") is None:
        print("[FAIL] trainer did not return a tool_mask (no tool call in the rollout?)")
        return 1

    completion_ids = captured["completion_ids"]
    completion_mask = captured["completion_mask"]
    tool_mask = captured["tool_mask"]

    total_masked = 0
    total_trained = 0
    masked_texts: list[str] = []
    print("\n=== token mask audit (first training micro-batch) ===")
    for i in range(completion_ids.size(0)):
        valid = int(completion_mask[i].sum())
        ids = completion_ids[i, :valid].tolist()
        tm = tool_mask[i, :valid].tolist()
        trained = sum(tm)
        masked = valid - trained
        total_trained += trained
        total_masked += masked
        print(f"\n--- sample {i}: valid={valid} trained={trained} masked={masked} "
              f"masked_ratio={masked / max(valid, 1):.2%} ---")
        for start, end, value in spans(tm):
            text = tokenizer.decode(ids[start:end], skip_special_tokens=False)
            text = text.replace("\n", "\\n")
            label = "TRAIN" if value == 1 else "MASK "
            print(f"  [{label}] {end - start:>4} tok | {text[:260]}")
            if value == 0:
                masked_texts.append(text)

    print(f"\n[totals] trained={total_trained} masked={total_masked} "
          f"masked_ratio={total_masked / max(total_trained + total_masked, 1):.2%}")

    # Basic invariant: the two masks agree on valid length, and at least one
    # tool-response span was actually excluded from the loss.
    assert total_masked > 0, "no tool-result tokens were masked"
    assert any("<tool_response>" in text for text in masked_texts), (
        "masked spans do not look like tool responses"
    )
    assert total_trained + total_masked == sum(int(completion_mask[i].sum()) for i in range(completion_ids.size(0)))
    print("\n[PASS] tool-result tokens are present in input_ids but excluded from the loss mask")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
